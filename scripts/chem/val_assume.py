def main():
    cfg = json.load(open(CFG, encoding="utf-8"))
    cos = json.load(open(os.path.join(ROOT, "docs", "chem", "data", "companies.json"), encoding="utf-8"))["companies"]
    grp = {c["code"]: c.get("group") for c in cos}
    bsd = {c["code"]: c.get("bs") for c in cos}
    out = {}
    for code, (pos, E1, g, r, c, note, ex) in A.items():
        cn = CYC.get(grp.get(code), "")
        if ex.get("skip"):
            out[code] = {"skip": ex["skip"], "cyc_pos": pos, "cycle_note": cn}
            continue
        d = {"cyc_pos": pos, "cycle_note": cn, "E1": E1, "g": dict(bear=g[0], base=g[1], bull=g[2]),
             "r": r, "c": c, "note": note}
        if pos == "호황 정점권" or "excess" in ex:
            d["excess"] = ex.get("excess", PEAK)
        bs = bsd.get(code) or {}
        if bs.get("debt") and (bs.get("cash") or 0) + (bs.get("st_fin") or 0) - bs["debt"] < 0:
            d["nc_adj"] = False  # 순차입 회사: 이자 비용이 이미 순이익에 들어 있어 차입금을 다시 빼지 않음
        for k in ("nc_adj", "ni_now", "ni_now_note"):
            if k in ex:
                d[k] = ex[k]
        if pos == "바닥권" and "excess" not in d and grp.get(code) == "석유화학(NCC·대형)":
            d["excess"] = SLOW
        out[code] = d
    miss = [c["code"] for c in cos if c["code"] not in out]
    assert not miss, miss
    cfg["companies"] = out
    cfg["industry_cycle"] = CYC
    cfg["asof"] = "2026-11-08"
    cfg["note"] = NOTE
    json.dump(cfg, open(CFG, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("companies:", len(out))


if __name__ == "__main__":
    main()
